import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createSettingsStore } from '../src/settings/settings.js';

const read = (p) => readFileSync(new URL('../' + p, import.meta.url), 'utf8');

test('settings: a write that does not land is reported once per change (and the change still applies for the session)', () => {
  const store = { map: new Map(), full: false, getItem(k) { return this.map.has(k) ? this.map.get(k) : null; }, setItem(k, v) { if (this.full) throw new Error('quota'); this.map.set(k, v); }, removeItem(k) { this.map.delete(k); } };
  let errs = 0;
  const s = createSettingsStore({ storage: store, onWriteError: () => { errs++; } });
  assert.equal(errs, 0);
  s.set('playback.shuffle', true); assert.equal(errs, 0, 'a healthy write is silent');
  store.full = true;
  assert.equal(s.set('playback.shuffle', false), true, 'the value is accepted for this session');
  assert.equal(s.get('playback.shuffle'), false);
  assert.equal(errs, 1);
  const quiet = createSettingsStore({ storage: store, onWriteError: () => { errs++; } });   // first-run write into a blocked store: nothing the user did, no toast
  void quiet; assert.equal(errs, 1);
});

